#!/usr/bin/env python3
"""Generate core-api's repeatable Flyway seed from data/taxonomy/skills.yaml.

Standard library only: the YAML file uses a flat, fixed shape (see its header).
Usage: python3 scripts/gen_skill_seed.py [--check]
  --check  exit 1 if the committed seed is out of date (used in CI).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data/taxonomy/skills.yaml"
TARGET = ROOT / "services/core-api/src/main/resources/db/migration/R__seed_skills.sql"
CATEGORIES = {"LANGUAGE", "FRAMEWORK", "DATABASE", "CLOUD", "DEVOPS", "AI", "PRACTICE", "SOFT", "OTHER"}
SLUG = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def parse(text: str) -> list[dict[str, object]]:
    skills: list[dict[str, object]] = []
    for raw in text.splitlines():
        line = raw.split(" #", 1)[0].rstrip() if not raw.lstrip().startswith("#") else ""
        if not line.strip():
            continue
        if line.startswith("- "):
            skills.append({})
            line = "  " + line[2:]
        if not skills or not line.startswith("  "):
            raise ValueError(f"unexpected line: {raw!r}")
        key, _, value = line.strip().partition(":")
        value = value.strip()
        if key == "aliases":
            inner = value.removeprefix("[").removesuffix("]")
            skills[-1][key] = [a.strip().lower() for a in inner.split(",") if a.strip()]
        else:
            skills[-1][key] = value
    return skills


def validate(skills: list[dict[str, object]]) -> None:
    seen: set[str] = set()
    for s in skills:
        slug, name, category = s.get("slug"), s.get("name"), s.get("category")
        if not isinstance(slug, str) or not SLUG.match(slug):
            raise ValueError(f"bad slug: {slug!r}")
        if not isinstance(name, str) or not name:
            raise ValueError(f"missing name for {slug}")
        if category not in CATEGORIES:
            raise ValueError(f"bad category for {slug}: {category!r}")
        terms = [slug, name.lower(), *s.get("aliases", [])]  # type: ignore[misc]
        for term in dict.fromkeys(terms):
            if term in seen:
                raise ValueError(f"alias {term!r} is used twice")
            seen.add(term)


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render(skills: list[dict[str, object]]) -> str:
    rows = ",\n".join(f"  ({q(str(s['slug']))}, {q(str(s['name']))}, {q(str(s['category']))})" for s in skills)
    alias_rows = []
    for s in skills:
        terms = dict.fromkeys([str(s["slug"]), str(s["name"]).lower(), *s.get("aliases", [])])  # type: ignore[misc]
        alias_rows += [f"  ({q(t)}, {q(str(s['slug']))})" for t in terms]
    return (
        "-- GENERATED by scripts/gen_skill_seed.py from data/taxonomy/skills.yaml. Do not edit.\n"
        "-- Repeatable migration: Flyway re-runs it whenever this file changes. Upserts only, never deletes\n"
        "-- (job_skill / user_skill reference skills).\n\n"
        "INSERT INTO skill (slug, name, category) VALUES\n"
        f"{rows}\n"
        "ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, category = EXCLUDED.category;\n\n"
        "INSERT INTO skill_alias (alias, skill_id)\n"
        "SELECT a.alias, s.id FROM (VALUES\n"
        f"{',\n'.join(alias_rows)}\n"
        ") AS a(alias, slug) JOIN skill s ON s.slug = a.slug\n"
        "ON CONFLICT (alias) DO UPDATE SET skill_id = EXCLUDED.skill_id;\n"
    )


def main() -> int:
    skills = parse(SOURCE.read_text(encoding="utf-8"))
    validate(skills)
    sql = render(skills)
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != sql:
            print(f"{TARGET.relative_to(ROOT)} is stale; run scripts/gen_skill_seed.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(sql, encoding="utf-8")
    print(f"wrote {len(skills)} skills to {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
